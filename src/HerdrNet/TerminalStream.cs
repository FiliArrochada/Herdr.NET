using System.Buffers.Binary;
using System.IO.Pipelines;
using System.Text.Json;
using HerdrNet.Framing;
using HerdrNet.Model;
using HerdrNet.Serialization;

namespace HerdrNet;

/// <summary>Why a terminal stream ended. Core reasons pass through as sent (<c>exited</c>, <c>killed</c>, <c>lost</c>, ...).</summary>
public static class TerminalCloseReasons
{
    /// <summary>This viewer detached (the core answered its CLOSE).</summary>
    public const string Detached = "detached";
    /// <summary>The program exited.</summary>
    public const string Exited = "exited";
    /// <summary>The program was killed.</summary>
    public const string Killed = "killed";
    /// <summary>The connection was closed by this client.</summary>
    public const string ConnectionClosed = "connection_closed";
    /// <summary>The connection was lost; the terminal may well still run: attach again after reconnecting.</summary>
    public const string ConnectionLost = "connection_lost";
    /// <summary>The core closed the stream with a reason this client could not read.</summary>
    public const string Unknown = "unknown";
}

/// <summary>How a terminal stream ended.</summary>
/// <param name="Reason">See <see cref="TerminalCloseReasons"/>; core reasons pass through.</param>
/// <param name="ExitCode">The program's exit code, when it exited.</param>
/// <param name="Signal">The signal that ended it, when one did.</param>
/// <param name="Error">The connection error, for <c>connection_lost</c>.</param>
public sealed record TerminalStreamClosed(string Reason, int? ExitCode, int? Signal, Exception? Error)
{
    /// <summary>True when the terminal itself may still be running (only this view of it ended).</summary>
    public bool TerminalMayStillRun => Reason is TerminalCloseReasons.Detached or TerminalCloseReasons.ConnectionClosed or TerminalCloseReasons.ConnectionLost;
}

/// <summary>
/// A live view of one terminal: the first paint and then the program's raw output on <see cref="Output"/>,
/// keys and size changes back. Output is a VT byte stream for a terminal emulator, not text lines.
/// Advancing <see cref="Output"/> returns flow-control credit to the core; a reader that stops reading
/// eventually gets a fresh repaint instead of the backlog. Disposing detaches; the program keeps running.
/// </summary>
public sealed class TerminalStream : IAsyncDisposable
{
    const int MaxInputFrame = 1024 * 1024;
    readonly ChannelEndpoint _channel;
    int _disposed;

    internal TerminalStream(ChannelEndpoint channel, AttachResult attach)
    {
        _channel = channel;
        Attach = attach;
        Completion = channel.Closed.ContinueWith(
            t => new TerminalStreamClosed(t.Result.Reason, t.Result.ExitCode, t.Result.Signal, t.Result.Error),
            CancellationToken.None, TaskContinuationOptions.ExecuteSynchronously, TaskScheduler.Default);
    }

    /// <summary>The attach reply: the terminal's facts and what the path negotiated.</summary>
    public AttachResult Attach { get; }

    /// <summary>The terminal's address.</summary>
    public string Terminal => Attach.Terminal.Address;

    /// <summary>The program's output (first paint, then live bytes). Completes when the stream ends.</summary>
    public PipeReader Output => _channel.Reader;

    /// <summary>Completes when the stream ends, saying why. Never faults.</summary>
    public Task<TerminalStreamClosed> Completion { get; }

    /// <summary>
    /// The core announced the terminal's grid (only when <see cref="TerminalAttachOptions.ResizeNotifications"/>
    /// was confirmed). Raised on the thread reading <see cref="Output"/>, inside its read, before any output
    /// byte that followed the announcement is returned: apply it before feeding the next bytes. The core
    /// follows each announcement with a fresh paint.
    /// </summary>
    public event Action<ushort, ushort>? Resized
    {
        add => _channel.ResizeReceived += value;
        remove => _channel.ResizeReceived -= value;
    }

    /// <summary>Sends keys or pasted bytes, as the person typed them.</summary>
    public async ValueTask WriteInputAsync(ReadOnlyMemory<byte> bytes, CancellationToken cancellationToken = default)
    {
        while (!bytes.IsEmpty)
        {
            var chunk = bytes[..Math.Min(bytes.Length, MaxInputFrame)];
            await _channel.SendAsync(FrameKind.Data, chunk, cancellationToken).ConfigureAwait(false);
            bytes = bytes[chunk.Length..];
        }
    }

    /// <summary>
    /// Sends bytes the terminal emulator generated by itself (query replies), which must not count as
    /// human activity. Falls back to plain input when the path did not confirm support.
    /// </summary>
    public ValueTask WriteAutomaticInputAsync(ReadOnlyMemory<byte> bytes, CancellationToken cancellationToken = default) =>
        Attach.AutomaticInput
            ? _channel.SendAsync(FrameKind.AutomaticInput, bytes, cancellationToken)
            : WriteInputAsync(bytes, cancellationToken);

    /// <summary>Tells the core this viewer's size in cells.</summary>
    public ValueTask ResizeAsync(ushort cols, ushort rows, CancellationToken cancellationToken = default)
    {
        var payload = new byte[4];
        BinaryPrimitives.WriteUInt16LittleEndian(payload, cols);
        BinaryPrimitives.WriteUInt16LittleEndian(payload.AsSpan(2), rows);
        return _channel.SendAsync(FrameKind.Resize, payload, cancellationToken);
    }

    /// <summary>Tells the core this viewer gained or lost focus.</summary>
    public ValueTask FocusAsync(bool focused, CancellationToken cancellationToken = default) =>
        _channel.SendAsync(FrameKind.Focus, new[] { focused ? (byte)1 : (byte)0 }, cancellationToken);

    /// <summary>Tells the core the viewer's colours and cell size.</summary>
    public ValueTask SetDisplayAsync(Display display, CancellationToken cancellationToken = default) =>
        _channel.SendAsync(FrameKind.Facts, JsonSerializer.SerializeToUtf8Bytes(display, HerdrJsonContext.Default.Display), cancellationToken);

    /// <summary>Detaches: sends CLOSE and waits briefly for the core's answer. The program keeps running.</summary>
    public async ValueTask DisposeAsync()
    {
        if (Interlocked.Exchange(ref _disposed, 1) != 0)
            return;
        await _channel.CloseAsync(TimeSpan.FromSeconds(2)).ConfigureAwait(false);
        await _channel.Reader.CompleteAsync().ConfigureAwait(false);
    }
}
